import pytest
from messages import plural_days


@pytest.mark.parametrize("count,expected", [
    # Базовые случаи
    (0,  "0 дней"),
    (1,  "1 день"),
    (2,  "2 дня"),
    (3,  "3 дня"),
    (4,  "4 дня"),
    (5,  "5 дней"),
    (9,  "9 дней"),
    (10, "10 дней"),
    # Особые случаи 11-19 (всегда «дней»)
    (11, "11 дней"),
    (12, "12 дней"),
    (13, "13 дней"),
    (14, "14 дней"),
    (19, "19 дней"),
    # После 19 — снова по последней цифре
    (20, "20 дней"),
    (21, "21 день"),
    (22, "22 дня"),
    (24, "24 дня"),
    (25, "25 дней"),
    # Сотни
    (100, "100 дней"),
    (101, "101 день"),
    (102, "102 дня"),
    (111, "111 дней"),   # 11 в конце — «дней»
    (121, "121 день"),
    # Большие числа
    (1000, "1000 дней"),
    (1001, "1001 день"),
    (1011, "1011 дней"),
    (1000001, "1000001 день"),
])
def test_plural_days(count, expected):
    assert plural_days(count) == expected
